"""Split every original Pretendard character; load current UI text together.

Requires fonttools[woff]. Generated assets are checked in; builds need no Python.
Keep original outlines, variable weights, layout features and a full-font fallback.
"""
import hashlib
from pathlib import Path
from fontTools import subset
from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
source = root / "public/assets/fonts/pretendard/PretendardVariable.woff2"
target = source.parent / "subsets"
target.mkdir(exist_ok=True)
original = TTFont(source, recalcTimestamp=False)
cmap = original.getBestCmap()
characters = set(range(0x20, 0x100)) | set(range(0x2000, 0x2070))
for path in sorted((root / "src").rglob("*")):
    if path.suffix in {".js", ".jsx", ".css"} and ".test." not in path.name and ".generated." not in path.name:
        characters.update(map(ord, path.read_text(encoding="utf-8")))
common = characters.intersection(cmap)
groups = {"common": common}
for point in sorted(set(cmap) - common):
    groups.setdefault(f"range-{point // 512:03x}", set()).add(point)

def unicode_range(points):
    spans = []
    first = last = None
    for point in sorted(points):
        if first is not None and point == last + 1:
            last = point
            continue
        if first is not None:
            spans.append(f"U+{first:X}" if first == last else f"U+{first:X}-{last:X}")
        first = last = point
    if first is not None:
        spans.append(f"U+{first:X}" if first == last else f"U+{first:X}-{last:X}")
    return ", ".join(spans)

faces = []
covered = set()
for name, points in groups.items():
    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.glyph_names = True
    options.notdef_outline = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    output = target / f"{name}.woff2"
    font.save(output)
    decoded = TTFont(output)
    assert set(decoded.getBestCmap()) == points
    assert not covered.intersection(points)
    covered.update(points)
    assert [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in original["fvar"].axes] == [(a.axisTag, a.minValue, a.defaultValue, a.maxValue) for a in decoded["fvar"].axes]
    # Check metrics and interpolated outlines at light, normal and bold weights.
    for weight in (100, 400, 700, 900):
        before = original.getGlyphSet(location={"wght": weight})
        after = decoded.getGlyphSet(location={"wght": weight})
        for point in points:
            glyph = cmap[point]
            assert decoded.getBestCmap()[point] == glyph
            a, b = RecordingPen(), RecordingPen()
            before[glyph].draw(a)
            after[glyph].draw(b)
            assert a.value == b.value, (name, hex(point), weight)
            assert before[glyph].width == after[glyph].width, (name, hex(point), weight)
    version = hashlib.sha256(output.read_bytes()).hexdigest()[:12]
    faces.append((f"/assets/fonts/pretendard/subsets/{name}.woff2?v={version}", unicode_range(points)))
    print(f"{name}: {len(points)} characters, {output.stat().st_size:,} bytes; four weights verified", flush=True)
assert covered == set(cmap), "Every original character must remain available"

def font_css(family):
    css = ["/* Generated by scripts/subset-game-fonts.py; disjoint ranges cover the full original cmap. */"]
    # Earlier full face also covers failed shard downloads. Later matching ranges win.
    # The full face keeps the original cmap range so emoji and other missing glyphs never fetch it.
    for url, span in [("/assets/fonts/pretendard/PretendardVariable.woff2", unicode_range(covered)), *faces]:
        css.append(f'@font-face {{\n  font-family: "{family}";\n  src: url("{url}") format("woff2");\n  font-style: normal;\n  font-weight: 100 900;\n  font-display: swap;\n  unicode-range: {span};\n}}')
    return "\n".join(css) + "\n"

css_root = root / "src/styles/pretendard"
css_root.mkdir(parents=True, exist_ok=True)
for filename, family in (("mypage", "MyPage Pretendard"), ("detail", "Detail Pretendard"), ("tooltip", "Board Tooltip Pretendard"), ("payment", "MSG Payment")):
    (css_root / f"{filename}.generated.css").write_text(font_css(family), encoding="utf-8")
# Game pages link this file at runtime (src/routes/pageResources.js) instead of the CDN Pretendard.
(source.parent / "pretendard.generated.css").write_text(font_css("Pretendard"), encoding="utf-8")
print(f"{len(groups)} shards cover all {len(covered):,} original characters", flush=True)
